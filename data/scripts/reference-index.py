#!/usr/bin/env python3
"""Regenerate the searchable reference index layer.

One store of archival bundles, many projects that link into it. Two roles:

  store <store-root>
      Rebuild the store's own searchable layer: the global catalog, the
      cross-bundle topic map, and every bundle's symbol map.

  view <project-references-dir>
      Rebuild one project's linked view from `<project-references-dir>/links.yaml`
      (the store path plus the `product/version` bundles this project uses), and
      that project's `knowledge/index.md`. The view is a projection of the store,
      never a copy of it, so a project can never drift into holding its own
      bundle or its own idea of which version is current.

Both roles derive everything from the same source of truth - each bundle's
`manifest.yaml` and its `content/*.md` front-matter. Neither reads the other's
output, so a project view cannot go stale relative to a second generated layer.

Status and supersession are carried into every generated file, so a consumer
resolving through `topics.yaml` can tell a current bundle from a superseded one
without opening the catalog.

Hand-authored content is preserved:
  - `<bundle>/index.md` is never modified.
  - `links.yaml` is never modified.
  - In generated files, text between `<!-- manual:begin -->` and `<!-- manual:end -->`
    is preserved across regeneration.

Usage:
  reference-index.py store <store-root> [--check] [--quiet]
  reference-index.py view <project-references-dir> [--check] [--quiet]

Exit codes:
  0  success (or, with --check, no drift)
  1  --check found drift, a broken link, or a hard error
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    yaml = None

FRONT_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n?", re.DOTALL)
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*$")
ANCHOR_RE = re.compile(r"\{#([A-Za-z0-9._-]+)\}\s*$")
GENERATED_NOTE = "generated by reference-index.py - do not edit by hand"

# A generated file must stay parseable as whatever it claims to be, so the
# annotation syntax follows the extension: HTML comments in markdown, `#` in YAML.
COMMENT_TEMPLATES = {".md": "<!-- {} -->", ".yaml": "# {}"}
ANNOTATABLE = ".md"

# The begin marker carries its own line terminator. If the newline between the two
# markers were added on the way out instead, it would be captured as inner content
# on the way back in and the block would grow by one line on every run.
MANUAL_BEGIN = f"<!-- manual:begin -->\n"
MANUAL_END = "<!-- manual:end -->"
MANUAL_RE = re.compile(
    r"<!--[ \t]*manual:begin[ \t]*-->(.*?)<!--[ \t]*manual:end[ \t]*-->", re.DOTALL
)


def comment(text: str, path: Path) -> str:
    return COMMENT_TEMPLATES.get(path.suffix, COMMENT_TEMPLATES[".md"]).format(text)


def manual_block(inner: str = "") -> str:
    """An annotator's own block, preserved across regeneration.

    Markdown only. There is no safe equivalent in YAML: free text inside a `#`
    comment stops being a comment, so a generated `topics.yaml` is owned outright
    and a note belongs in the bundle's hand-authored `index.md` instead.
    """
    return MANUAL_BEGIN + inner + MANUAL_END


def slugify(text: str) -> str:
    text = text.strip().lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-") or "section"


def parse_front_matter(text: str):
    match = FRONT_RE.match(text)
    if not match:
        return {}, text
    meta = {}
    raw = match.group(1)
    if yaml is not None:
        try:
            loaded = yaml.safe_load(raw)
            if isinstance(loaded, dict):
                meta = loaded
        except yaml.YAMLError:
            meta = {}
    body = text[match.end():]
    return meta, body


def iter_headings(body: str):
    seen = {}
    for line in body.splitlines():
        match = HEADING_RE.match(line)
        if not match:
            continue
        title = match.group(2).strip()
        anchor_match = ANCHOR_RE.search(title)
        if anchor_match:
            anchor = anchor_match.group(1)
            title = ANCHOR_RE.sub("", title).strip()
        else:
            anchor = slugify(title)
        if anchor in seen:
            seen[anchor] += 1
            anchor = f"{anchor}-{seen[anchor]}"
        else:
            seen[anchor] = 1
        yield int(len(match.group(1))), title, anchor


def estimate_tokens(text: str) -> int:
    stripped = re.sub(r"\s+", " ", text).strip()
    return max(1, round(len(stripped) / 4))


def as_list(value) -> list:
    if value is None:
        return []
    if isinstance(value, (list, tuple)):
        return [str(v).strip() for v in value if str(v).strip()]
    return [str(value).strip()]


def display_path(path: Path) -> str:
    """Render a path for citation: `~/...` under the home directory, else absolute.

    Citations end up in knowledge items and task packets that outlive the session,
    so a `~/`-rooted path stays openable without also carrying the store root.
    """
    resolved = Path(path).resolve()
    home = Path(os.path.expanduser("~")).resolve()
    try:
        return "~/" + resolved.relative_to(home).as_posix()
    except ValueError:
        return resolved.as_posix()


def read_manual(path: Path) -> str:
    """The annotator's own block, preserved verbatim; a blank one for markdown
    that has none yet. Formats the generator owns outright (`.yaml`) get "" -
    they are rewritten whole."""
    if path.suffix != ANNOTATABLE:
        return ""
    match = MANUAL_RE.search(path.read_text(encoding="utf-8")) if path.exists() else None
    return match.group(0) if match else manual_block()


def render(path: Path, body: str, manual: str) -> str:
    parts = [comment(GENERATED_NOTE, path), body.rstrip(), manual.rstrip()]
    return "\n\n".join(parts) + "\n"


def collect_bundle(bundle_dir: Path) -> dict:
    """One bundle: manifest, content files, and the identity a link names."""
    manifest = {}
    manifest_path = bundle_dir / "manifest.yaml"
    if manifest_path.exists() and yaml is not None:
        try:
            manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError:
            manifest = {}
    if not isinstance(manifest, dict):
        manifest = {}

    # Identity is the store-relative path, because that is what a link names.
    # `product` in the manifest is a display label and need not match the
    # directory, so it must not be what a `links.yaml` entry has to reproduce.
    key = f"{bundle_dir.parent.name}/{bundle_dir.name}"
    product = str(manifest.get("product") or bundle_dir.parent.name)
    version = str(manifest.get("version") or bundle_dir.name)

    files = []
    content = bundle_dir / "content"
    if content.is_dir():
        for path in sorted(content.rglob("*.md")):
            text = path.read_text(encoding="utf-8", errors="replace")
            meta, body = parse_front_matter(text)
            files.append(
                {
                    "rel": path.relative_to(bundle_dir).as_posix(),
                    "meta": meta,
                    "headings": list(iter_headings(body)),
                    "tokens": int(meta.get("tokens") or estimate_tokens(body)),
                }
            )

    return {
        "dir": bundle_dir,
        "manifest": manifest,
        "product": product,
        "version": version,
        "key": key,
        "status": str(manifest.get("status") or "current"),
        "superseded_by": str(manifest.get("superseded_by") or ""),
        "retrieved": str(manifest.get("retrieved") or "-"),
        "files": files,
    }


def collect_store(store_root: Path) -> list:
    """Every bundle in the store, keyed by the `product/version` a link names."""
    bundles = [
        collect_bundle(p.parent)
        for p in sorted(store_root.glob("*/*/manifest.yaml"))
    ]
    bundles.sort(key=lambda b: b["key"].lower())
    return bundles


def pick_anchor(headings, topic: str) -> str:
    """Best heading anchor for a topic.

    Returns "" when no heading matches. Falling back to the file's first heading
    would point a topic at unrelated prose, and a wrong anchor is worse than a
    miss: the consumer cannot tell it was misled. A file-level pointer (empty
    anchor) is honest and still bounded by the file's token estimate.
    """
    if not headings:
        return ""
    wanted = slugify(topic)
    stem = wanted.rstrip("s")
    for _level, title, anchor in headings:
        hay = f"{anchor} {slugify(title)}"
        if wanted in hay or (len(stem) > 3 and stem in hay):
            return anchor
    return ""


def bundle_topics(bundle) -> list:
    return sorted({t for f in bundle["files"] for t in as_list(f["meta"].get("topics"))})


def build_catalog(bundles, store_display: str, heading: str, blurb: str) -> str:
    lines = [heading, "", blurb, "", f"Store: `{store_display}`", ""]
    if not bundles:
        lines.append("_No bundles._")
        return "\n".join(lines) + "\n"
    lines.append("| key | status | superseded by | topics | files | tokens | retrieved |")
    lines.append("|-----|--------|---------------|--------|-------|--------|-----------|")
    for b in bundles:
        tokens = sum(f["tokens"] for f in b["files"])
        topics = ", ".join(bundle_topics(b)) or "-"
        lines.append(
            f"| `{b['key']}` | {b['status']} | {b['superseded_by'] or '-'} | "
            f"{topics} | {len(b['files'])} | ~{tokens} | {b['retrieved']} |"
        )
    return "\n".join(lines) + "\n"


def build_topics(bundles, store_display: str) -> tuple:
    """topic -> list of anchors. Returns (yaml_text, unmapped_topic_file_pairs)."""
    topics = {}
    unmapped = []
    for b in bundles:
        for f in b["files"]:
            title = f["headings"][0][1] if f["headings"] else f["rel"]
            rel_ref = f"{b['key']}/{f['rel']}"
            for topic in as_list(f["meta"].get("topics")):
                anchor = pick_anchor(f["headings"], topic)
                if not anchor:
                    unmapped.append(f"{topic} -> {rel_ref}")
                ref = f"{store_display}/{rel_ref}" + (f"#{anchor}" if anchor else "")
                entry = {"ref": ref, "version": b["version"], "status": b["status"]}
                if b["superseded_by"]:
                    entry["superseded_by"] = b["superseded_by"]
                entry["title"] = title
                topics.setdefault(topic, []).append(entry)
    if yaml is None:
        return "# generated (yaml module unavailable)\n{}\n", unmapped
    body = yaml.safe_dump(dict(sorted(topics.items())), sort_keys=False, allow_unicode=True)
    return f"# store: {store_display}\n{body}", unmapped


def build_api_index(bundle) -> str:
    name, version = bundle["product"], bundle["version"]
    status, superseded_by = bundle["status"], bundle["superseded_by"]
    rows = []
    for f in bundle["files"]:
        anchor = f["headings"][0][2] if f["headings"] else ""
        loc = f["rel"] + (f"#{anchor}" if anchor else "")
        for symbol in as_list(f["meta"].get("symbols")):
            rows.append((str(symbol), loc))
    rows.sort(key=lambda r: r[0].lower())
    body = [f"# API index - {name} {version}", ""]
    if superseded_by:
        body.append(
            f"Status: **{status}** - superseded by `{superseded_by}`. Use that bundle instead."
        )
        body.append("")
    body.append("| symbol | location | status |")
    body.append("|--------|----------|--------|")
    if rows:
        for symbol, loc in rows:
            body.append(f"| {symbol} | `{loc}` | {status} |")
    else:
        body.append("| _no symbols declared in content front-matter_ | - | - |")
    return "\n".join(body) + "\n"


def build_knowledge_index(knowledge_dir: Path) -> str:
    """Compact map over `knowledge/` items, so the cheap tier cannot drift.

    The path relative to the knowledge root doubles as the pointer consumers
    read; `title` and `source` come from item front-matter.
    """
    rows = []
    for path in sorted(knowledge_dir.rglob("*.md")):
        if path.name == "index.md":
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        meta, body = parse_front_matter(text)
        rel = path.relative_to(knowledge_dir).as_posix()
        first = next(iter_headings(body), None)
        title = str(meta.get("title") or (first[1] if first else rel))
        source = str(meta.get("source") or "-")
        tokens = int(meta.get("tokens") or estimate_tokens(body))
        rows.append((rel, title, f"~{tokens}", source))
    body = [
        "# Knowledge index",
        "",
        "Compact map of `knowledge/`. Read an item only when its row is the cheapest sufficient entry.",
        "",
    ]
    if rows:
        body.append("| item | title | tokens | source |")
        body.append("|------|-------|--------|--------|")
        for rel, title, tokens, source in rows:
            body.append(f"| `{rel}` | {title} | {tokens} | `{source}` |")
    else:
        body.append("_No knowledge items._")
    return "\n".join(body) + "\n"


def write_generated(path: Path, body: str, check: bool, drift, quiet: bool):
    new = render(path, body, read_manual(path))
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == new:
        return
    if check:
        drift.append(str(path))
        return
    path.write_text(new, encoding="utf-8")
    if not quiet:
        print(f"wrote {path}")


def load_links(view_dir: Path) -> tuple:
    """The project's link key: (store path, [product/version], parse error)."""
    links_path = view_dir / "links.yaml"
    if not links_path.exists():
        return None, [], f"no {links_path} - a project's references/ needs a link key"

    data = {}
    if yaml is not None:
        try:
            loaded = yaml.safe_load(links_path.read_text(encoding="utf-8"))
            if isinstance(loaded, dict):
                data = loaded
        except yaml.YAMLError as exc:
            return None, [], f"{links_path}: {exc}"

    store = data.get("store")
    if not store:
        return None, [], f"{links_path}: missing `store`"

    keys = [k for k in as_list(data.get("links"))]
    bad = [k for k in keys if k.count("/") != 1 or k.startswith("/") or k.endswith("/")]
    if bad:
        return None, [], (
            f"{links_path}: links must be `<product>/<version>`; bad entries: "
            + ", ".join(bad)
        )
    return Path(str(store)).expanduser(), keys, None


def cmd_store(root: Path, args) -> int:
    if not root.is_dir():
        print(f"reference-index: not a directory: {root}", file=sys.stderr)
        return 1

    bundles = collect_store(root)
    store_display = display_path(root)
    drift = []

    write_generated(
        root / "index.md",
        build_catalog(
            bundles,
            store_display,
            "# Reference store",
            "Every bundle held in this store. Projects reach these through their "
            "own `references/links.yaml`; a project that does not link a bundle "
            "must not use it.",
        ),
        args.check,
        drift,
        args.quiet,
    )
    topics_text, unmapped = build_topics(bundles, store_display)
    write_generated(root / "topics.yaml", topics_text, args.check, drift, args.quiet)
    for bundle in bundles:
        write_generated(
            bundle["dir"] / "api-index.md",
            build_api_index(bundle),
            args.check,
            drift,
            args.quiet,
        )

    report_unmapped(unmapped, args.quiet)
    return finish(args, drift, f"{len(bundles)} bundle(s) indexed in the store")


def cmd_view(view_dir: Path, args) -> int:
    if not view_dir.is_dir():
        print(f"reference-index: not a directory: {view_dir}", file=sys.stderr)
        return 1

    store, keys, error = load_links(view_dir)
    if error:
        print(f"reference-index: {error}", file=sys.stderr)
        return 1
    if not store.is_dir():
        print(f"reference-index: store not found: {store}", file=sys.stderr)
        return 1

    available = {b["key"]: b for b in collect_store(store)}
    missing = [k for k in keys if k not in available]
    if missing:
        # A link to a bundle that is not in the store is exactly the drift this
        # layout exists to catch, so it is a hard error rather than a warning.
        print(
            "reference-index: links in "
            f"{view_dir / 'links.yaml'} point at bundles the store does not hold: "
            + ", ".join(missing)
            + f" (store: {display_path(store)})",
            file=sys.stderr,
        )
        return 1

    selected = [available[k] for k in keys]
    superseded = [b["key"] for b in selected if b["status"] != "current"]
    store_display = display_path(store)
    drift = []

    # A zero-link view must not carry the store total: the store is shared, so that
    # count moves whenever any other project ingests, and it would flag this view as
    # drifted for a number that says nothing about this project. A linked view keeps
    # the ratio, which is project information and says the view is a filtered subset.
    scope = (
        f" ({len(selected)} of {len(available)} in the store)"
        if selected
        else " — this project links none"
    )
    blurb = f"Linked bundles only{scope}. Edit `links.yaml`, not this file."
    write_generated(
        view_dir / "index.md",
        build_catalog(selected, store_display, "# Linked references", blurb),
        args.check,
        drift,
        args.quiet,
    )
    topics_text, unmapped = build_topics(selected, store_display)
    write_generated(view_dir / "topics.yaml", topics_text, args.check, drift, args.quiet)

    # A project's knowledge tree shares this store, so it gets the same treatment:
    # hand-maintaining a second index over the same material is how the cheap
    # tier drifts out from under the correct one.
    knowledge_dir = view_dir.parent / "knowledge"
    if knowledge_dir.is_dir() and any(knowledge_dir.rglob("*.md")):
        write_generated(
            knowledge_dir / "index.md",
            build_knowledge_index(knowledge_dir),
            args.check,
            drift,
            args.quiet,
        )

    if superseded and not args.quiet:
        print(
            "reference-index: these linked bundles are not current - repoint "
            "links.yaml at the replacement:\n  " + "\n  ".join(superseded),
            file=sys.stderr,
        )
    report_unmapped(unmapped, args.quiet)
    return finish(args, drift, f"{len(selected)} linked bundle(s) projected")


def report_unmapped(unmapped, quiet: bool) -> None:
    if unmapped and not quiet:
        print(
            "reference-index: no heading matched these topics; emitted file-level "
            "pointers instead (add a matching heading or fix the front-matter):\n  "
            + "\n  ".join(unmapped),
            file=sys.stderr,
        )


def finish(args, drift, done: str) -> int:
    if args.check:
        if drift:
            print("reference-index: drift in:\n  " + "\n  ".join(drift), file=sys.stderr)
            return 1
        if not args.quiet:
            print("reference-index: indexes up to date")
    elif not args.quiet:
        print(f"reference-index: {done}")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("role", choices=["store", "view"], help="what to regenerate")
    parser.add_argument("root", help="store root (store) or project references/ (view)")
    parser.add_argument("--check", action="store_true", help="report drift, do not write")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    if yaml is None:
        print("reference-index: PyYAML is required (pip install pyyaml)", file=sys.stderr)
        return 1

    root = Path(args.root).expanduser().resolve()
    return cmd_store(root, args) if args.role == "store" else cmd_view(root, args)


if __name__ == "__main__":
    raise SystemExit(main())
