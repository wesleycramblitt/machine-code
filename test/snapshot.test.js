/**
 * Committed model snapshot: deterministic TOML serialization of the catalogue
 * model table, and the shipped data/models.toml file itself.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { parse } from "smol-toml";
import { serializeModelsSnapshot } from "../dist/catalogue/snapshot.js";

function row(key, overrides = {}) {
  return {
    key,
    providerID: key.split("/")[0],
    id: key.slice(key.indexOf("/") + 1),
    name: `Model ${key}`,
    family: "Test",
    releaseDate: "2026-01-01",
    context: 128_000,
    maxOutput: 16_000,
    reasoning: true,
    toolCall: true,
    image: false,
    capabilities: {
      reasoning: true,
      toolCall: true,
      image: false,
      input: ["text"],
      output: ["text"],
      contextWindow: 128_000,
      maxOutputTokens: 16_000,
    },
    kind: "chat",
    coding: true,
    modes: ["reasoning", "tools"],
    free: false,
    canonicalID: `owner/${key.split("/")[1]}`,
    pricing: {
      input: 1,
      output: 2,
      cacheRead: 0.1,
      cacheWrite: 0.2,
      tiers: [{ size: 100_000, input: 2, output: 3, cacheRead: 0.2, cacheWrite: 0.3 }],
    },
    benchmarks: { source: "test", sweBench: 70 },
    scores: { reasoning: 8, code: 7, agentic: 6, general: 5, capability: 6.6 },
    tokensPerSecond: 42,
    provenance: {
      metadata: "generated",
      benchmark: "test",
      estimated: false,
      estimatedFields: [],
      curated: ["reasoning"],
      scoreSources: { reasoning: "benchmark", code: "metadata", agentic: "benchmark", general: "metadata" },
    },
    ...overrides,
  };
}

test("snapshot serializes all rows deterministically, sorted by key", () => {
  const doc = {
    version: 1,
    generatedAt: "2026-01-01T00:00:00.000Z",
    providers: {},
    sources: [],
    models: [row("p/b"), row("p/a")],
  };
  const text = serializeModelsSnapshot(doc);
  assert.equal(text, serializeModelsSnapshot(doc));
  assert.match(text, /Generated by `machine_code catalogue snapshot`/);
  const parsed = parse(text);
  assert.equal(parsed.meta.model_count, 2);
  assert.equal(parsed.meta.offer_count, 2);
  assert.deepEqual(Object.keys(parsed.models), ["owner/a", "owner/b"]);
  const a = parsed.models["owner/a"];
  assert.equal(a.kind, "chat");
  assert.equal(a.coding, true);
  assert.deepEqual(a.capabilities.input, ["text"]);
  assert.equal(a.score_sources.reasoning, "benchmark");
  assert.equal(a.score_sources.code, undefined, "metadata axes are omitted");
  assert.equal(a.provenance.estimated, false);
  assert.equal(a.benchmarks.sweBench, 70);
  const offer = a.offers["p/a"];
  assert.equal(offer.pricing.tiers[0].size, 100_000);
  assert.equal(offer.tokens_per_second, 42);
});

test("canonical model keeps capabilities once; offers keep only differences", () => {
  const paid = row("openrouter/owner/model", {
    canonicalID: "owner/model",
    context: 200_000,
    maxOutput: 32_000,
    pricing: { input: 1, output: 2, cacheRead: 0.1, cacheWrite: 0.2 },
  });
  const free = row("free/owner/model", {
    canonicalID: "owner/model",
    context: 64_000,
    maxOutput: 8_000,
    free: true,
    pricing: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
  });
  const parsed = parse(
    serializeModelsSnapshot({
      version: 1,
      generatedAt: "2026-01-01T00:00:00.000Z",
      providers: {},
      sources: [],
      models: [paid, free],
    }),
  );
  assert.equal(parsed.meta.model_count, 1);
  assert.equal(parsed.meta.offer_count, 2);
  const model = parsed.models["owner/model"];
  assert.equal(model.context, 200_000);
  assert.equal(model.max_output, 32_000);
  assert.deepEqual(Object.keys(model.offers).sort(), [
    "free/owner/model",
    "openrouter/owner/model",
  ]);
  assert.equal(model.offers["free/owner/model"].free, true);
  assert.equal(model.offers["free/owner/model"].context, 64_000);
  assert.equal(model.offers["free/owner/model"].max_output, 8_000);
  assert.equal(model.offers["openrouter/owner/model"].context, undefined);
});

test("shipped data/models.toml is a valid, complete snapshot", () => {
  const parsed = parse(readFileSync(new URL("../data/models.toml", import.meta.url), "utf8"));
  const keys = Object.keys(parsed.models);
  assert.equal(parsed.meta.model_count, keys.length);
  assert.ok(keys.length > 100, "snapshot contains the current catalogue");
  const offers = Object.values(parsed.models).reduce((n, model) => n + Object.keys(model.offers).length, 0);
  assert.equal(parsed.meta.offer_count, offers);
  const sample = parsed.models["openai/gpt-6-luna-pro"];
  assert.ok(sample, "known model is present");
  assert.equal(sample.kind, "chat");
  assert.equal(sample.coding, true);
  assert.ok(sample.capabilities.input.includes("text"));
  assert.ok(Array.isArray(sample.modes));
  assert.equal(typeof sample.scores.capability, "number");
  assert.ok(sample.offers["openrouter/openai/gpt-6-luna-pro"]);
  const image = parsed.models["google/gemini-3-1-flash-lite-image"];
  assert.equal(image.kind, "image");
  assert.equal(image.coding, false);
});
